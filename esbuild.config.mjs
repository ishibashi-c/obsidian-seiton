import { readFile } from "node:fs/promises";
import process from "node:process";
import builtins from "builtin-modules";
import esbuild from "esbuild";

const licenseFiles = [
  "third_party/react/LICENSE",
  "third_party/date-fns/LICENSE",
  "third_party/easy-obookshelf/LICENSE",
  "third_party/link-card-preview/LICENSE",
  "third_party/selection-format-toolbar/LICENSE",
];
const licenses = await Promise.all(
  licenseFiles.map(async (file) => `${file}\n${await readFile(file, "utf8")}`)
);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin.

Third-party licenses:
${licenses.join("\n\n")}
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  bundle: true,
  entryPoints: ["src/main.ts"],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  loader: { ".css": "text" },
  logLevel: "info",
  minify: prod,
  outfile: "main.js",
  sourcemap: prod ? false : "inline",
  target: "es2018",
  treeShaking: true,
});

const styleContext = await esbuild.context({
  bundle: true,
  entryPoints: ["src/ui/styles.css"],
  logLevel: "info",
  minify: prod,
  outfile: "styles.css",
  target: "es2018",
});

if (prod) {
  await context.rebuild();
  await styleContext.rebuild();
  process.exit(0);
} else {
  await context.watch();
  await styleContext.watch();
}
